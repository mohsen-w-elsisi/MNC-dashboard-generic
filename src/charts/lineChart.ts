const root = am5.Root.new("market-share-timeseries");
const chart = root.container.children.push(
  am5xy.XYChart.new(root, { panX: true, wheelX: "panX", wheelY: "zoomX" }),
);

const xAxis = chart.xAxes.push(
  am5xy.DateAxis.new(root, {
    baseInterval: { timeUnit: "year", count: 1 },
    gridIntervals: [{ timeUnit: "year", count: 1 }],
    renderer: am5xy.AxisRendererX.new(root, {}),
  }),
);

const yAxis = chart.yAxes.push(
  am5xy.ValueAxis.new(root, {
    // max: 100,
    min: 0,
    renderer: am5xy.AxisRendererY.new(root, {}),
  }),
);

new Set(data.map(({ Country }) => Country)).forEach((country) => {
  const series = chart.series.push(
    am5xy.LineSeries.new(root, {
      xAxis,
      yAxis,
      valueYField: "Our_Company",
      valueXField: "date",
      name: country,
      hue: Math.random() * 360,
    }),
  );

  series.strokes.template.setAll({strokeWidth: 3})

  series.data.setAll(data.filter((d) => d.Country === country));
});
